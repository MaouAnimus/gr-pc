"""Audit the current game's TLS instructions with local LLVM; write a version-bound profile."""
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import json

ROOT = Path(__file__).resolve().parents[1]


def main():
    data = (ROOT / 'CUSA01130/eboot.bin').read_bytes()
    count = struct.unpack_from('<H', data, 0x18)[0]
    entries = [struct.unpack_from('<QQQQ', data, 0x20 + i * 32) for i in range(count)]
    text = [entry for entry in entries if entry[0] & 0x800 and ((entry[0] >> 20) & 0xfff) == 0]
    if len(text) != 1 or text[0][0] & 3:
        raise ValueError('requires the known uncompressed SELF text segment')
    _, offset, size, _ = text[0]
    code = data[offset:offset + size]
    # This SELF has no section table: identify its contiguous import PLT and
    # audit the instruction area through that table, excluding embedded assets.
    plt = list(re.finditer(b'\xff\x25....\x68....\xe9....', code, re.DOTALL))
    if not plt or any(right.start() != left.end() for left, right in zip(plt, plt[1:])):
        raise ValueError('cannot establish a contiguous PLT boundary for this profile')
    instruction_end = plt[-1].end()
    code = code[:instruction_end]
    size = len(code)
    names = b'\0.text\0.shstrtab\0'
    sections = (0x100 + len(code) + 0x100) & ~0xff
    image = bytearray(sections + 192 + len(names))
    image[:64] = struct.pack('<16sHHIQQQIHHHHHH', b'\x7fELF\x02\x01\x01' + bytes(9),
        1, 62, 1, 0, 0, sections, 0, 64, 56, 0, 64, 3, 2)
    image[0x100:0x100 + size] = code
    image[sections + 64:sections + 128] = struct.pack('<IIQQQQIIQQ', 1, 1, 6, 0, 0x100, size, 0, 0, 16, 0)
    image[sections + 128:sections + 192] = struct.pack('<IIQQQQIIQQ', 7, 3, 0, 0, sections + 192, len(names), 0, 0, 1, 0)
    image[sections + 192:] = names
    target = ROOT / 'out/evidence/tls_profile_text.elf'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(image)
    command = ['rtk', 'proxy', r'C:\msys64\clang64\bin\llvm-objdump.exe', '-d', '--x86-asm-syntax=intel', str(target)]
    process = subprocess.Popen(command, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    offsets, unsupported = [], []
    for line in process.stdout:
        if 'fs:' not in line:
            continue
        match = re.match(r'\s*([0-9a-f]+):\s+((?:[0-9a-f]{2}\s+)+)', line)
        if not match:
            unsupported.append(line.strip()); continue
        address = int(match[1], 16)
        decoded = bytes.fromhex(match[2])
        if (len(decoded) == 9 and decoded[:3] in [b'\x64\x48\x8b', b'\x64\x4c\x8b'] and
            decoded[3] & 0xc7 == 4 and decoded[4:] == b'\x25\0\0\0\0' and code[address:address + 9] == decoded):
            offsets.append(address)
        else:
            unsupported.append(line.strip())
    errors = process.stderr.read()
    if process.wait():
        raise RuntimeError(errors)
    digest = hashlib.sha256(data).hexdigest()
    report = {'source': 'CUSA01130/eboot.bin', 'sha256': digest,
              'method': 'Local LLVM disassembly, not REA; linear text sweep, not control-flow proof',
              'text_file_offset': offset, 'text_size': size, 'fixup_count': len(offsets),
              'scope': 'Executable prefix through contiguous import PLT; remaining load-segment bytes excluded',
              'offsets': [hex(x) for x in offsets], 'unsupported_fs': unsupported,
              'llvm_version': subprocess.check_output(['rtk', 'proxy', r'C:\msys64\clang64\bin\llvm-objdump.exe', '--version'], text=True).splitlines()[0]}
    (ROOT / 'docs/evidence/tls_fixup_profile.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    if unsupported:
        raise RuntimeError(f'{len(unsupported)} unsupported FS instructions: ' + '\n'.join(unsupported[:10]))
    header = '// Generated by tools/generate_tls_profile.py; changes require a new executable audit.\n'
    header += f'constexpr char profile_sha256[] = "{digest}";\n'
    header += 'constexpr std::uint32_t profile_offsets[] = {\n'
    for start in range(0, len(offsets), 10):
        header += '    ' + ', '.join(hex(x) for x in offsets[start:start + 10]) + ',\n'
    header += '};\n'
    (ROOT / 'engine/src/loader/gravity_tls_profile.inc').write_text(header, encoding='utf-8')
    print(f'Profile: SHA256={digest}; audited TLS fixups={len(offsets)}; unsupported FS={len(unsupported)}')


if __name__ == '__main__':
    main()
